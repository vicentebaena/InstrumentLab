const countedCircuit={sample(time){const input=[0,.5,0,1,0,.5,0,1,0][Math.max(0,Math.min(8,Math.floor(time*9)))];return {input,output:input};}};
const countedGenerator={...generator,frequency:1};
const countedVoltage=scope.voltageStatistics(countedCircuit,{},countedGenerator,settings,{},0,1,1);
const countedTime=scope.timeStatistics(countedCircuit,{},countedGenerator,settings,{},0,1,1,countedVoltage);
for(const name of ['+Pulses','-Pulses','+Edges','-Edges']) {
 assert.equal(countedTime[name],2,name);assert.equal(scope.formatTimeMeasurement(countedTime[name],name),'2');
}
const rateGenerator={...generator,waveform:'sine',offset:0};
const rateVoltage=scope.voltageStatistics(circuit,circuit.defaults,rateGenerator,settings,{},0,.002,1);
const rateTime=scope.timeStatistics(circuit,circuit.defaults,rateGenerator,settings,{},0,.002,1,rateVoltage);
close(rateTime['+Rate'],.8*rateVoltage.Vpp/rateTime['Rise Time']);
close(rateTime['-Rate'],-.8*rateVoltage.Vpp/rateTime['Fall Time']);
assert.ok(rateTime['+Rate']>0);assert.ok(rateTime['-Rate']<0);
assert.match(scope.formatTimeMeasurement(rateTime['+Rate'],'+Rate'),/kV\/s$/);
assert.equal(scope.formatTimeMeasurement(timing['+Rate'],'+Rate'),'*****','instantaneous ideal edges have no finite rate');
