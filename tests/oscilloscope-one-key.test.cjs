assert.deepEqual(Array.from(scope.oneKeyParameters(settings).slice(18)),['PhaseRise','PhaseFall']);
controller.actions.oneKeyMeasurement(0);assert.match(render(),/Phas1→2↑=(?!\*\*\*\*\*)[^<]*°/);
settings.channels[2].visible=false;assert.match(render(),/Phas1→2↑=\*\*\*\*\*/);
console.log('Completed horizontal groups: qualified counts, signed transition rates, CH1→CH2 delay/phase and unavailable-source handling.');

// Area integrates signed displayed voltage; Per.Area integrates a whole period only.
const areaState=scope.createState({channels:{1:{voltsPerDivision:1}}});
let area=scope.voltageStatistics(circuit,circuit.defaults,generator,areaState,{1:1},0,.002,1);
close(area.Area,.002);close(area['Per.Area'],.001);
assert.equal(scope.formatVoltageMeasurement(area.Area,'Area'),'2.00mVs');
assert.equal(scope.formatVoltageMeasurement(area['Per.Area'],'Per.Area'),'1.00mVs');
areaState.channels[1].probe=2;areaState.channels[1].inverted=true;
area=scope.voltageStatistics(circuit,circuit.defaults,generator,areaState,{1:10},0,.002,1);
close(area.Area,-.0004);close(area['Per.Area'],-.0002);
areaState.channels[1].coupling='AC';
area=scope.voltageStatistics(circuit,circuit.defaults,generator,areaState,{1:10},0,.002,1);
close(area.Area,0);close(area['Per.Area'],0);
Object.assign(areaState.channels[1],{probe:1,inverted:false,coupling:'DC'});
area=scope.voltageStatistics(circuit,circuit.defaults,generator,areaState,{},.0001,.0002,1);
close(area.Area,.0004);assert.equal(area['Per.Area'],0);
const fallbackArea=scope.voltageStatistics({...circuit,mean:undefined},circuit.defaults,generator,areaState,{},0,.002,1);
close(fallbackArea['Per.Area'],.001);
console.log('Area/Per.Area: signed integration, full-period mean, AC/probe/inversion transforms, short-window zero, squared-independent units and numerical fallback.');
