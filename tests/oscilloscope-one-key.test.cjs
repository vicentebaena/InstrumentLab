'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const context=vm.createContext({window:{}});
for(const file of ['circuits.js','oscilloscope.js','oscilloscope-controller.js'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../app',file),'utf8'),context);
const app=context.window.InstrumentLab,scope=app.oscilloscope,circuit=app.circuits.rc;
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`${a} != ${b}`);
const generator={...app.generatorDefaults,waveform:'square',frequency:1000,offset:1,amplitudeVpp:2};
let settings=scope.createState({channels:{1:{voltsPerDivision:1}}},4);
const voltage=scope.voltageStatistics(circuit,circuit.defaults,generator,settings,{},0,.001,1);
for(const [parameter,value] of Object.entries({Vmax:2,Vmin:0,Vpp:2,Vtop:2,Vbase:0,Vamp:2,Vupper:1.8,Vmid:1,Vlower:.2,Vavg:1,Vrms:Math.sqrt(2),Variance:1,Overshoot:0,Preshoot:0}))close(voltage[parameter],value);
assert.equal(scope.formatVoltageMeasurement(1,'Variance'),'1.00V²');
assert.equal(scope.formatVoltageMeasurement(.000004,'Variance'),'4.00mV²');
assert.equal(scope.formatVoltageMeasurement(undefined,'Variance'),'*****');
const sine=scope.voltageStatistics(circuit,circuit.defaults,{...generator,waveform:'sine'},settings,{},0,.001,1);
close(sine.Variance,.5);assert.equal(sine.Vupper,undefined);
const independent=scope.createState({},4);settings.oneKey.measurements.push({channel:1,parameter:'Vpp'});assert.equal(independent.oneKey.measurements.length,0);
settings=scope.createState({channels:{1:{voltsPerDivision:1}}},4);
let liveGenerator={...generator};
const controller=app.createOscilloscopeController({getSettings:()=>settings,setSettings:s=>settings=s,onChange(){},onAuto(){settings=scope.createState({},4);},getExperiment:()=>({circuit,parameters:circuit.defaults,generator:liveGenerator,probes:{1:1,2:1}}),t:k=>k,format:String});
const render=()=>controller.getDisplay({traceLayerOnly:true,oneKeyMeasurements:true,horizontalDivisions:12,cellWidth:48});
for(let slot=0;slot<6;slot++)controller.actions.oneKeyMeasurement(slot);
assert.equal(settings.oneKey.measurements.length,5);
assert.equal(settings.oneKey.measurements[0].parameter,'Vmin');
controller.actions.oneKeyMeasurement(2);assert.equal(settings.oneKey.measurements.length,5);
assert.equal(settings.oneKey.measurements.at(-1).parameter,'Vpp');
assert.ok(render().includes('Vpp=2.00V'));
controller.actions.runStop();liveGenerator.amplitudeVpp=1;
assert.ok(render().includes('Vpp=2.00V'),'STOP retains captured waveform inputs for one-key readings');
controller.actions.runStop();assert.ok(render().includes('Vpp=1.00V'));
controller.actions.channel(3);controller.actions.oneKeyMeasurement(0);
assert.match(render(),/data-one-key-parameter="Vmax" data-one-key-channel="3"[^>]*>Vmax=\*\*\*\*\*/);
controller.actions.channel(1);controller.actions.oneKeyMeasurement(0);liveGenerator.output1Enabled=false;
assert.match(render(),/data-one-key-parameter="Vmax" data-one-key-channel="1"[^>]*>Vmax=\*\*\*\*\*/);
assert.deepEqual(Array.from(scope.submenus.measureVoltage.options),['Vmax','Vmin','Vpp','Vtop','Vbase','Vamp','Vavg','Vrms','Overshoot','Preshoot']);
console.log('One-key numerical measures: fourteen voltage parameters, squared variance units, independent state, five live slots, deduplication, STOP capture, no-input placeholders and old model options.');

// Ten time parameters from manual p140 reuse common time measurements.
controller.actions.auto();liveGenerator={...generator,offset:0};
settings.channels[1].voltsPerDivision=1;
controller.actions.oneKeyType();assert.equal(settings.oneKey.kind,'time');
const voltageForTime=scope.voltageStatistics(circuit,circuit.defaults,liveGenerator,settings,{},0,.002,1);
const timing=scope.timeStatistics(circuit,circuit.defaults,liveGenerator,settings,{},0,.002,1,voltageForTime);
close(timing.Period,.001);close(timing.Freq,1000);close(timing['+Width'],.0005);close(timing['-Width'],.0005);
close(timing['+Duty'],50);close(timing['-Duty'],50);close(timing['Rise Time'],0);close(timing['Fall Time'],0);
assert.ok(timing.tVmax>=-.001 && timing.tVmax<=.001);assert.ok(timing.tVmin>=-.001 && timing.tVmin<=.001);
close(timing.tVmax,voltageForTime.tVmax-.001);close(timing.tVmin,voltageForTime.tVmin-.001);
controller.actions.oneKeyMeasurement(0);controller.actions.oneKeyMeasurement(1);
assert.ok(render().includes('Period=1.00ms'));assert.ok(render().includes('Freq=1.00kHz'));
controller.actions.oneKeyPage(1);controller.actions.oneKeyMeasurement(0);
assert.ok(render().includes('+Duty=50.00%'));
controller.actions.oneKeyPage(1);controller.actions.oneKeyMeasurement(0);assert.ok(render().includes('data-one-key-parameter="tVmax"'));
controller.actions.oneKeyType();assert.equal(settings.oneKey.kind,'voltage');assert.equal(settings.oneKey.page,0);
assert.equal(settings.oneKey.measurements.length,4);
console.log('Horizontal one-key: period, frequency, 10–90% transitions, widths, duty and trigger-relative tVmax/tVmin, mixed readings and menu switching.');

