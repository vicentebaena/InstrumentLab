'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context=vm.createContext({window:{}});
for(const f of ['circuits.js','oscilloscope.js','translations.js'])vm.runInContext(fs.readFileSync('app/'+f,'utf8'),context);
const app=context.window.InstrumentLab,scope=app.oscilloscope;
let state=scope.createState();
const draw=()=>scope.render(app.circuits.rc,app.circuits.rc.defaults,app.generatorDefaults,k=>app.translations.en[k],String,'test',12,state,{cellWidth:40,footerScales:true});
assert.ok(!draw().includes('data-cursors="X"'));
state=scope.pressCursors(state);
let svg=draw();
assert.ok(svg.includes('data-cursor="A" x1="196" x2="196"'));
assert.ok(svg.includes('data-cursor="B" x1="356" x2="356"'));
for(const value of ['CurA:-400us','CurB:400us','|ΔX|:800us','|1/ΔX|:1.25kHz'])assert.ok(svg.includes(value),value);
state=scope.toggleChannelMenu(state);assert.ok(draw().includes('data-cursors="X"'),'menu hiding does not disable cursors');
state.channels[2].visible=false;assert.ok(draw().includes('data-cursors="X"'));
state.channels[1].visible=false;assert.ok(!draw().includes('data-cursor-readings'));
state.channels[2].visible=true;state.cursors.source=2;assert.ok(draw().includes('data-cursor-source="2"'));
state.horizontalPositionDivisions=1;
svg=draw();assert.ok(svg.includes('CurA:-600us'));assert.ok(svg.includes('CurB:200us'));assert.ok(svg.includes('|ΔX|:800us'));
state.timePerDivision=.001;svg=draw();assert.ok(svg.includes('|ΔX|:4.00ms'));assert.ok(svg.includes('|1/ΔX|:250Hz'));
state.acquisitionRunning=false;assert.ok(draw().includes('data-cursors="X"'));
state=scope.createState();assert.ok(!draw().includes('data-cursors="X"'));
assert.equal(scope.formatCursorValue(-.00198),'-1.98ms');assert.equal(scope.formatCursorValue(.000620),'620us');assert.equal(scope.formatCursorValue(1/.000620,true),'1.61kHz');
console.log('X cursors: initial positions, source visibility, menu independence, common time axis, formatting and reset passed.');
state=scope.createState({cursorsEnabled:true,cursorsMenuOpen:true,cursors:{selectedA:true}});
const a0=state.cursors.positionA,b0=state.cursors.positionB;
state=scope.stepSelection(state,1);
assert.ok(state.cursors.positionA>a0);assert.equal(state.cursors.positionB,b0);
assert.ok(draw().includes(`x1="${36+480*state.cursors.positionA}"`));
state.cursors.selectedB=true;
const separation=state.cursors.positionB-state.cursors.positionA;
state=scope.stepSelection(state,1);
assert.ok(Math.abs(state.cursors.positionB-state.cursors.positionA-separation)<1e-12);
const positions=[state.cursors.positionA,state.cursors.positionB];
state=scope.openSubmenu(state,'cursorSource');state=scope.stepSelection(state,1);
assert.equal(state.submenuSelection,2);assert.deepEqual([state.cursors.positionA,state.cursors.positionB],positions);
state=scope.stepSelection(state,1);assert.deepEqual([state.cursors.positionA,state.cursors.positionB],positions,'submenu boundary must not move cursors');
state=scope.confirmSubmenu(state);state.channels[2].visible=false;
const hidden=state;assert.equal(scope.stepSelection(state,1),hidden);
state.channels[2].visible=true;
for(let i=0;i<300;i++)state=scope.stepSelection(state,1);
assert.ok(Math.abs(state.cursors.positionB-1)<1e-12);
assert.ok(Math.abs(state.cursors.positionB-state.cursors.positionA-separation)<1e-12);
for(let i=0;i<300;i++)state=scope.stepSelection(state,-1);
assert.ok(Math.abs(state.cursors.positionA)<1e-12);
assert.ok(Math.abs(state.cursors.positionB-state.cursors.positionA-separation)<1e-12);
state.cursors.positionB=state.cursors.positionA;
assert.ok(!draw().includes('Infinity'));assert.ok(draw().includes('∞Hz'));
console.log('Cursor movement: independent/joint steps, shared clamping, readout updates, hidden source and submenu priority passed.');
state=scope.createState({cursorsEnabled:true,cursorsMenuOpen:true,cursors:{source:2,positionYA:.25,positionYB:.75,selectedA:true},channels:{2:{voltsPerDivision:2,positionDivisions:1}}});
state=scope.toggleCursorType(state);
assert.equal(state.cursors.type,'Y');
svg=draw();assert.ok(svg.includes('data-cursors="Y"'));
assert.ok(svg.includes('data-cursor="A" x1="36" x2="516" y1="124" y2="124"'));
for(const reading of ['CurA:2.00V','CurB:-6.00V','|ΔY|:8.00V'])assert.ok(svg.includes(reading),reading);
assert.ok(!svg.includes('|1/ΔX|'));
const oldY=state.cursors.positionYA;state=scope.stepSelection(state,1);assert.ok(state.cursors.positionYA<oldY,'clockwise raises horizontal cursor');
state.cursors.selectedB=true;
const ySeparation=state.cursors.positionYB-state.cursors.positionYA;
for(let i=0;i<300;i++)state=scope.stepSelection(state,1);
assert.ok(Math.abs(state.cursors.positionYA)<1e-12);
assert.ok(Math.abs(state.cursors.positionYB-state.cursors.positionYA-ySeparation)<1e-12);
const yPositions=[state.cursors.positionYA,state.cursors.positionYB];
state=scope.openSubmenu(state,'cursorSource');state=scope.stepSelection(state,-1);
assert.deepEqual([state.cursors.positionYA,state.cursors.positionYB],yPositions);
state=scope.confirmSubmenu(state);
state=scope.toggleCursorType(state);assert.equal(state.cursors.type,'X');
assert.equal(state.cursors.positionA,1/3);assert.equal(state.cursors.positionB,2/3);
state=scope.toggleCursorType(state);assert.deepEqual([state.cursors.positionYA,state.cursors.positionYB],yPositions);
state.channels[state.cursors.source].visible=false;assert.ok(!draw().includes('data-cursors="Y"'));
console.log('Y cursors: horizontal geometry, source voltage scale/ground, three readings, movement, priority and separate X/Y positions passed.');
