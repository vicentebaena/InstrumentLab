'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const c={window:{InstrumentLab:{}}};vm.runInNewContext(fs.readFileSync('app/oscilloscope.js','utf8'),c);
const scope=c.window.InstrumentLab.oscilloscope,definition=scope.submenus.measureVoltage;
let state=scope.openMeasureMenu(scope.createState());state=scope.openSubmenu(state,'measureVoltage');
const page=()=>scope.submenuPage(definition.options,state.submenuSelection,4,state.submenuPageStart);
assert.equal(page().start,0);assert.equal(page().previous,false);assert.equal(page().next,true);
for(let i=0;i<4;i++)state=scope.stepSelection(state,1);
assert.equal(state.submenuSelection,'Vbase');assert.equal(page().start,4);assert.equal(page().previous,true);assert.equal(page().next,true);
for(let i=0;i<4;i++)state=scope.stepSelection(state,1);
assert.equal(state.submenuSelection,'Overshoot');assert.equal(page().start,6);assert.equal(page().next,false);
assert.equal(page().values.join(','),'Vavg,Vrms,Overshoot,Preshoot');
state=scope.stepSelection(state,-1);assert.equal(state.submenuSelection,'Vrms');assert.equal(page().start,6);
state=scope.stepSelection(state,-1);assert.equal(state.submenuSelection,'Vavg');assert.equal(page().start,6);
state=scope.stepSelection(state,-1);assert.equal(state.submenuSelection,'Vamp');assert.equal(page().start,4);
for(let i=0;i<30;i++)state=scope.stepSelection(state,-1);
assert.equal(state.submenuSelection,'Vmax');assert.equal(page().start,0);
for(let i=0;i<30;i++)state=scope.stepSelection(state,1);
assert.equal(state.submenuSelection,'Preshoot');assert.equal(page().start,6);
state=scope.confirmSubmenu(state);assert.equal(state.measure.voltage,'Preshoot');assert.equal(state.submenu,null);
state=scope.openSubmenu(state,'measureVoltage');assert.equal(page().start,6);
state=scope.toggleChannelMenu(state);assert.equal(state.submenu,null);
console.log('Voltage pages: 1–4/5–8/7–10, overlap retained while navigating backward, arrows, non-wrapping boundaries and confirmation passed.');
